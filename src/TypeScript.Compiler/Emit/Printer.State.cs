/// <summary>ported from: src/compiler/emitter.ts:6351-6361 — <c>OrdinalParentheizerRuleSelector</c>.</summary>
/// <remarks>
/// PORT-NOTE: the reference's interface has one member, <c>select(index) =&gt; parenthesizerRule | undefined</c>. The
/// printer builds exactly one such value (for type arguments, emitter.ts:1277-1279), so the port states it as a
/// sealed class with the same single member rather than an interface plus an implementation. The type parameter is
/// constrained to the model's <see cref="INode"/> rather than to <see cref="Node"/>, because the one list it is built
/// for is a <c>NodeArray&lt;ITypeNode&gt;</c> and the port's unions are interfaces (<c>Model/NodeInterfaces.cs</c>);
/// every member of those lists is a <see cref="Node"/> at run time, which is what the list machinery casts on.
/// </remarks>
internal sealed class OrdinalParenthesizerRuleSelector<TNode>
    where TNode : INode
{
    private readonly Func<int, Func<TNode, TNode>?> _select;

    public OrdinalParenthesizerRuleSelector(Func<int, Func<TNode, TNode>?> select) => _select = select;

    public Func<TNode, TNode>? Select(int index) => _select(index);
}

