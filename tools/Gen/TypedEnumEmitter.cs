using System.Text;

namespace TypeScript.Compiler.Tools;

/// <summary>
/// Generates the member half of <c>TypedEnum</c>: one nested type per <c>SyntaxKind</c> member, plus the
/// <c>FromSyntaxKind</c> reverse lookup that backs the dynamic path.
/// </summary>
/// <remarks>
/// TS uses enum members as types (`createToken(token: SyntaxKind.EndOfFileToken): EndOfFileToken`), which lets the
/// factory pick a return type from an argument, and also uses a runtime <c>SyntaxKind</c> value against an
/// <c>@internal</c> wide overload. C# needs both spelled out, and both need one nested type per member — about 350
/// of them, which is why this is generated rather than written (docs/architecture.md §16).
/// <para>
/// Two kinds of member are skipped. An alias (<c>FirstAssignment = EqualsToken</c>) is the same kind under a second
/// name, so a type for it would only make the reverse lookup ambiguous. <c>Count</c> is a sentinel rather than a
/// kind.
/// </para>
/// </remarks>
internal static class TypedEnumEmitter
{
    /// <summary>The TS file the members are declared in.</summary>
    public const string SourcePath = "src/compiler/types.ts";

    public static GeneratedFile Emit(TsModel model, string outputRoot)
    {
        var kinds = Kinds(model);

        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated>");
        sb.AppendLine($"//   Generated from {SourcePath} by tools/Gen — DO NOT EDIT.");
        sb.AppendLine("//   Regenerate with:");
        sb.AppendLine("//     dotnet run --project tools/Gen -- --out src/TypeScript.Compiler");
        sb.AppendLine("// </auto-generated>");
        sb.AppendLine();
        // Roslyn does not apply the project's nullable context to files marked <auto-generated>.
        sb.AppendLine("#nullable enable");
        sb.AppendLine();
        sb.AppendLine("namespace TypeScript.Compiler;");
        sb.AppendLine();
        sb.AppendLine("/// <summary>");
        sb.AppendLine("/// The generated half of <see cref=\"TypedEnum\"/> — one nested type per <c>SyntaxKind</c> member.");
        sb.AppendLine("/// </summary>");
        sb.AppendLine("/// <remarks>");
        sb.AppendLine("/// The hand-written half (Model/TypedEnum.cs) declares <see cref=\"ITypedEnum\"/> and the base class;");
        sb.AppendLine("/// this half is the members. Aliases and the <c>Count</c> sentinel have no type — see TypedEnumEmitter.");
        sb.AppendLine("/// </remarks>");
        sb.AppendLine("internal static partial class TypedEnum");
        sb.AppendLine("{");

        foreach (var member in kinds)
        {
            sb.AppendLine($"    // ported from: {SourcePath} — SyntaxKind.{member.Name} = {member.Value}");
            sb.AppendLine($"    internal sealed class {member.Name} : TypedEnum<{member.Name}>, ITypedEnum<{member.Name}>");
            sb.AppendLine("    {");
            sb.AppendLine($"        public static {member.Name} Instance {{ get; }} = new();");
            sb.AppendLine($"        public static SyntaxKind StaticSyntaxKind => SyntaxKind.{member.Name};");
            sb.AppendLine($"        public SyntaxKind SyntaxKind => SyntaxKind.{member.Name};");
            sb.AppendLine($"        private {member.Name}() {{ }}");
            sb.AppendLine("    }");
            sb.AppendLine();
        }

        AppendReverseLookup(sb, kinds);
        sb.AppendLine("}");

        // The repository is LF-only (.gitattributes: eol=lf); AppendLine emits CRLF on Windows.
        return new GeneratedFile($"{outputRoot}/Model/TypedEnum.Members.cs", sb.ToString().Replace("\r\n", "\n"));
    }

    /// <summary>
    /// The <c>SyntaxKind</c> members that get a nested type — exactly the names <c>TypedEnum.X</c> can use.
    /// </summary>
    /// <remarks>
    /// The type mapper needs this same list: `SyntaxKind.EndOfFileToken` as a parameter type has to become
    /// <c>TypedEnum.EndOfFileToken</c>, while an alias (<c>FirstAssignment</c>) or the <c>Count</c> sentinel has no
    /// type to name and stays <c>SyntaxKind</c>.
    /// </remarks>
    public static List<string> MemberNames(TsModel model)
        => Kinds(model).Select(static member => member.Name).ToList();

    private static List<TsEnumMember> Kinds(TsModel model)
    {
        var syntaxKind = model.Enums.FirstOrDefault(e => e.Name == "SyntaxKind")
            ?? throw new InvalidOperationException("the model has no SyntaxKind enum");

        // One type per distinct kind. Aliases and the Count sentinel are dropped (see the class remarks).
        return syntaxKind.Members
            .Where(static member => !member.IsAlias && member.Name != "Count")
            .ToList();
    }

    /// <summary>
    /// The dynamic path: <c>SyntaxKind</c> value back to the member type.
    /// </summary>
    /// <remarks>
    /// PORT-NOTE: the switch has one arm per kind, in declaration order. Aliases are already gone, so no two arms
    /// share a value — a duplicate would be a compile error, which is the desired failure mode.
    /// </remarks>
    private static void AppendReverseLookup(StringBuilder sb, List<TsEnumMember> kinds)
    {
        sb.AppendLine("    /// <summary>");
        sb.AppendLine("    /// The dynamic path: a <c>SyntaxKind</c> value that was not known at compile time back to its member.");
        sb.AppendLine("    /// </summary>");
        sb.AppendLine("    /// <remarks>");
        sb.AppendLine("    /// Returns <c>null</c> for a value no member has (the aliases and the <c>Count</c> sentinel included).");
        sb.AppendLine("    /// </remarks>");
        sb.AppendLine("    public static ITypedEnum? FromSyntaxKind(SyntaxKind kind) => kind switch");
        sb.AppendLine("    {");

        foreach (var member in kinds)
        {
            sb.AppendLine($"        SyntaxKind.{member.Name} => {member.Name}.Instance,");
        }

        sb.AppendLine("        _ => null,");
        sb.AppendLine("    };");
    }
}
