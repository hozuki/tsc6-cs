using System.Text;
using System.Text.RegularExpressions;

namespace TypeScript.Compiler.Tools;

/// <summary>
/// Generates <c>Parser/ForEachChildTable.cs</c> — the port of <c>parser.ts</c>'s <c>forEachChildTable</c>,
/// <c>forEachChild</c> and <c>forEachChildRecursively</c> (docs/architecture.md §11.3).
/// </summary>
/// <remarks>
/// The table maps each container <c>SyntaxKind</c> to a <c>||</c>-chain of child visits; that order is the
/// language service's contract, so the body is generated from the TS source rather than transcribed. The
/// extractor only accepts the shapes <c>parser.ts</c> writes (see <see cref="TsForEachChildVisit"/>) and aborts
/// otherwise.
/// <para>
/// Each kind gets its own private visitor that casts to the concrete node class, rather than several kinds
/// sharing the TS visitor that serves them. TS's shared visitors take a <em>union</em> of node types and read a
/// member that union has in common; C# has no structural union, and for two of them — the optional/rest/JSDoc
/// parameter modifiers and the call/new pair — the members are not on any common C# base (<c>Node</c> declares
/// neither <c>Type</c> nor <c>QuestionDotToken</c>). Per-kind methods are also what TSGO generates.
/// </para>
/// </remarks>
internal static class ForEachChildEmitter
{
    /// <summary>The source the table is derived from, relative to the TypeScript checkout.</summary>
    public const string SourcePath = "src/compiler/parser.ts";

    /// <summary>A visit the port cannot express because the concrete class has no such member.</summary>
    private static readonly HashSet<string> s_nodeMembers = new(StringComparer.Ordinal)
    {
        "kind", "flags", "modifierFlagsTransform", "transformFlags", "id", "parent", "original", "emitNode", "pos", "end",
    };

    public static GeneratedFile Emit(
        TsForEachChild table,
        TsModel model,
        TsTypeModel typeModel,
        TsTypeMapper mapper,
        string outputRoot,
        out List<(string Kind, string Member, string Reason)> dropped)
    {
        var syntaxKind = model.Enums.FirstOrDefault(static e => e.Name == "SyntaxKind")
            ?? throw new InvalidOperationException("forEachChild: the SyntaxKind enum was not extracted");
        var knownKinds = new HashSet<string>(syntaxKind.Members.Select(static m => m.Name), StringComparer.Ordinal);

        // One entry per kind; the class is the generated node class whose Kind is that kind.
        var visitsByKind = new List<(TsForEachChildEntry Entry, TsInterface NodeClass, string ClassName)>();
        dropped = [];

        foreach (var entry in table.Entries)
        {
            if (!knownKinds.Contains(entry.Kind))
            {
                throw new InvalidOperationException(
                    $"forEachChild: SyntaxKind.{entry.Kind} (parser.ts:{entry.Line}) is not a member of the SyntaxKind enum");
            }

            var classes = model.Interfaces.Where(i => i.ConcreteKind == entry.Kind).ToList();
            if (classes.Count == 0)
            {
                throw new InvalidOperationException(
                    $"forEachChild: no node interface has kind SyntaxKind.{entry.Kind} (parser.ts:{entry.Line})");
            }

            // A derived class may pin the same kind as its base — `JsonMinusNumericLiteral` is a
            // `PrefixUnaryExpression` with `Kind => SyntaxKind.PrefixUnaryExpression`. The visitor reads the
            // members from the base's perspective, so the widest claimant is the cast target; anything else is an
            // ambiguous kind the emitter must not guess at.
            var nodeClass = classes.Count == 1
                ? classes[0]
                : classes.FirstOrDefault(candidate => classes.All(other => ReferenceEquals(other, candidate) || IsAncestor(typeModel, candidate.Name, other.Name)))
                    ?? throw new InvalidOperationException(
                        $"forEachChild: SyntaxKind.{entry.Kind} (parser.ts:{entry.Line}) is claimed by {string.Join(", ", classes.Select(static c => c.Name))} with no common base");

            visitsByKind.Add((entry, nodeClass, mapper.TypeName(nodeClass.Name)));
        }

        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated>");
        sb.AppendLine($"//   Generated from {SourcePath} by tools/Gen — DO NOT EDIT.");
        sb.AppendLine($"//     forEachChildTable       {table.StartLine}-{table.EndLine}");
        foreach (var fn in table.Functions)
        {
            sb.AppendLine($"//     {fn.Name,-23} {fn.StartLine}-{fn.EndLine}");
        }

        sb.AppendLine("//   Regenerate with:");
        sb.AppendLine("//     dotnet run --project tools/Gen -- --out src/TypeScript.Compiler");
        sb.AppendLine("// </auto-generated>");
        sb.AppendLine();
        // Roslyn does not apply the project's nullable context to files marked <auto-generated>.
        sb.AppendLine("#nullable enable");
        sb.AppendLine();
        sb.AppendLine("namespace TypeScript.Compiler;");
        sb.AppendLine();
        AppendClassDoc(sb);
        sb.AppendLine("internal static partial class ForEachChildTable");
        sb.AppendLine("{");

        AppendDispatch(sb, visitsByKind);
        AppendFixedRuntime(sb);

        // One visitor per kind, in table order.
        foreach (var (entry, nodeClass, className) in visitsByKind)
        {
            AppendVisitor(sb, typeModel, mapper, entry, nodeClass, className, dropped);
        }

        sb.AppendLine("}");

        // The repository is LF-only (.gitattributes: eol=lf); AppendLine emits CRLF on Windows.
        var content = sb.ToString().Replace("\r\n", "\n");

        // A dropped visit is a child the port would silently not visit if it were wrong, so it is handed back
        // (which the generator reports) as well as written into the file.
        return new GeneratedFile($"{outputRoot}/Parser/ForEachChildTable.cs", content);
    }

    private static void AppendClassDoc(StringBuilder sb)
    {
        sb.AppendLine("/// <summary>");
        sb.AppendLine("/// Child traversal — the port of <c>parser.ts</c>'s <c>forEachChild</c>, <c>forEachChildRecursively</c>");
        sb.AppendLine("/// and the kind table that drives them.");
        sb.AppendLine("/// </summary>");
        sb.AppendLine("/// <remarks>");
        sb.AppendLine("/// <para>");
        sb.AppendLine("/// PORT-NOTE: TS writes each visitor as a chain of <c>||</c> expressions, and <c>||</c> tests");
        sb.AppendLine("/// <em>truthiness</em>: a callback returning <c>false</c> or <c>0</c> lets the chain continue, and only a");
        sb.AppendLine("/// truthy result stops it. Every step below therefore tests its result with <see cref=\"Js.IsTruthy(object?)\"/>");
        sb.AppendLine("/// rather than for null.");
        sb.AppendLine("/// </para>");
        sb.AppendLine("/// <para>");
        sb.AppendLine("/// PORT-NOTE: the array callback takes <c>INodeArray&lt;INode&gt;</c>, not <c>INodeArray&lt;Node&gt;</c>.");
        sb.AppendLine("/// TS's <c>NodeArray&lt;T&gt;</c> is covariant, so one callback serves arrays of any element type; the port's");
        sb.AppendLine("/// <see cref=\"INodeArray{T}\"/> is covariant too, but <c>NodeArray&lt;IStatement&gt;</c> converts only to");
        sb.AppendLine("/// <c>INodeArray&lt;INode&gt;</c> — the categorisation interfaces (<c>IStatement</c>, <c>ITypeNode</c>, …) derive");
        sb.AppendLine("/// from <see cref=\"INode\"/>, not from the <see cref=\"Node\"/> class, and a C# variance conversion needs an");
        sb.AppendLine("/// implicit conversion between the element types. The array itself is still what the callback receives:");
        sb.AppendLine("/// nothing is copied or flattened.");
        sb.AppendLine("/// </para>");
        sb.AppendLine("/// <para>");
        sb.AppendLine("/// PORT-NOTE: <see cref=\"ForEachChildRecursively\"/> walks an explicit stack instead of recursing, for the");
        sb.AppendLine("/// same reason TS does: a left-leaning tree can be deeper than the call stack (a 20k-deep one is covered by");
        sb.AppendLine("/// <c>ForEachChildTests</c>), so a recursive port would overflow. <c>GatherPossibleChildren</c> prepends each");
        sb.AppendLine("/// child and the walk pops, which is what makes the result a depth-first pre-order walk.");
        sb.AppendLine("/// </para>");
        sb.AppendLine("/// <para>");
        sb.AppendLine("/// PORT-NOTE: each kind gets its own visitor that casts <see cref=\"Node\"/> to the concrete class. Several");
        sb.AppendLine("/// kinds share one TS visitor, but that visitor's parameter is a union of node types; C# has no structural");
        sb.AppendLine("/// union, and for the optional/rest/JSDoc groups the common C# base (<c>Node</c>) does not declare the members");
        sb.AppendLine("/// being visited. TS's <c>(node as CallExpression).questionDotToken</c> is handled by omitting the step where");
        sb.AppendLine("/// the concrete class has no such member, which is exactly what TS reads there (undefined, so the visit is");
        sb.AppendLine("/// skipped). Every such omission is called out in the visitor's comment.");
        sb.AppendLine("/// </para>");
        sb.AppendLine("/// </remarks>");
    }

    private static void AppendDispatch(StringBuilder sb, List<(TsForEachChildEntry Entry, TsInterface NodeClass, string ClassName)> visits)
    {
        sb.AppendLine("    /// <summary>");
        sb.AppendLine("    /// Invokes <paramref name=\"cbNode\"/> for each child node of <paramref name=\"node\"/>, in source order, and");
        sb.AppendLine("    /// <paramref name=\"cbNodes\"/> for each embedded array instead of its elements. Stops at the first truthy");
        sb.AppendLine("    /// result and returns it; otherwise returns <c>default</c>.");
        sb.AppendLine("    /// </summary>");
        sb.AppendLine("    /// <remarks>");
        sb.AppendLine("    /// PORT-NOTE: the type is <c>ForEachChildTable</c> rather than TS's <c>forEachChild</c> because C# forbids");
        sb.AppendLine("    /// a member with the same name as its enclosing type (CS0542). The class takes TS's own name for the table");
        sb.AppendLine("    /// (parser.ts:505), leaving the entry point's name intact, so a call site maps 1:1 onto TS.");
        sb.AppendLine("    /// TS also returns immediately for <c>node === undefined</c>; the parameter here is non-nullable, so only");
        sb.AppendLine("    /// the token test remains — a token has no children.");
        sb.AppendLine("    /// </remarks>");
        sb.AppendLine("    public static T? ForEachChild<T>(Node node, Func<Node, T?> cbNode, Func<INodeArray<INode>, T?>? cbNodes = null)");
        sb.AppendLine("    {");
        sb.AppendLine("        if (node.Kind <= SyntaxKind.LastToken)");
        sb.AppendLine("        {");
        sb.AppendLine("            return default;");
        sb.AppendLine("        }");
        sb.AppendLine();
        sb.AppendLine("        switch (node.Kind)");
        sb.AppendLine("        {");
        foreach (var (entry, _, _) in visits)
        {
            sb.AppendLine($"            // ported from: {SourcePath}:{entry.Line}");
            sb.AppendLine($"            case SyntaxKind.{entry.Kind}: return ForEachChildIn{entry.Kind}(node, cbNode, cbNodes);");
        }

        sb.AppendLine("            default: return default;");
        sb.AppendLine("        }");
        sb.AppendLine("    }");
        sb.AppendLine();
    }

    private static void AppendFixedRuntime(StringBuilder sb)
    {
        sb.AppendLine("    /// <summary>");
        sb.AppendLine("    /// The <c>\"skip\"</c> sentinel a <see cref=\"ForEachChildRecursively\"/> callback returns to stop the walk");
        sb.AppendLine("    /// from descending into a node or an array.");
        sb.AppendLine("    /// </summary>");
        sb.AppendLine("    /// <remarks>");
        sb.AppendLine("    /// PORT-NOTE: TS compares the callback result against the string literal <c>\"skip\"</c>. A C#");
        sb.AppendLine("    /// <c>string</c> would be indistinguishable from a legitimate result, so the sentinel is the singleton of");
        sb.AppendLine("    /// a private marker type: it can only be produced by referring to this field.");
        sb.AppendLine("    /// </remarks>");
        sb.AppendLine("    public static readonly object Skip = SkipMarker.Instance;");
        sb.AppendLine();
        sb.AppendLine("    /// <summary>");
        sb.AppendLine("    /// Walks the tree under <paramref name=\"rootNode\"/> depth-first in pre-order without using the call stack,");
        sb.AppendLine("    /// calling <paramref name=\"cbNode\"/>/<paramref name=\"cbNodes\"/> with each node/array and its parent.");
        sb.AppendLine("    /// Returns the first non-<see cref=\"Skip\"/> truthy result, or <c>null</c>.");
        sb.AppendLine("    /// </summary>");
        sb.AppendLine("    public static object? ForEachChildRecursively(Node rootNode, Func<Node, Node, object?> cbNode, Func<INodeArray<INode>, Node, object?>? cbNodes = null)");
        sb.AppendLine("    {");
        sb.AppendLine("        var queue = GatherPossibleChildren(rootNode);");
        sb.AppendLine("        var parents = new List<Node>();");
        sb.AppendLine("        while (parents.Count < queue.Count)");
        sb.AppendLine("        {");
        sb.AppendLine("            parents.Add(rootNode);");
        sb.AppendLine("        }");
        sb.AppendLine();
        sb.AppendLine("        while (queue.Count != 0)");
        sb.AppendLine("        {");
        sb.AppendLine("            var current = queue[^1];");
        sb.AppendLine("            var parent = parents[^1];");
        sb.AppendLine("            queue.RemoveAt(queue.Count - 1);");
        sb.AppendLine("            parents.RemoveAt(parents.Count - 1);");
        sb.AppendLine();
        sb.AppendLine("            if (current is INodeArray<INode> nodes)");
        sb.AppendLine("            {");
        sb.AppendLine("                if (cbNodes is not null)");
        sb.AppendLine("                {");
        sb.AppendLine("                    var result = cbNodes(nodes, parent);");
        sb.AppendLine("                    if (Js.IsTruthy(result))");
        sb.AppendLine("                    {");
        sb.AppendLine("                        if (ReferenceEquals(result, Skip)) continue;");
        sb.AppendLine("                        return result;");
        sb.AppendLine("                    }");
        sb.AppendLine("                }");
        sb.AppendLine();
        sb.AppendLine("                // Reversed, so that popping visits the elements in order.");
        sb.AppendLine("                for (var i = nodes.Count - 1; i >= 0; --i)");
        sb.AppendLine("                {");
        sb.AppendLine("                    queue.Add(nodes[i]);");
        sb.AppendLine("                    parents.Add(parent);");
        sb.AppendLine("                }");
        sb.AppendLine("            }");
        sb.AppendLine("            else");
        sb.AppendLine("            {");
        sb.AppendLine("                var node = (Node)current;");
        sb.AppendLine("                var result = cbNode(node, parent);");
        sb.AppendLine("                if (Js.IsTruthy(result))");
        sb.AppendLine("                {");
        sb.AppendLine("                    if (ReferenceEquals(result, Skip)) continue;");
        sb.AppendLine("                    return result;");
        sb.AppendLine("                }");
        sb.AppendLine();
        sb.AppendLine("                if (node.Kind >= SyntaxKind.FirstNode)");
        sb.AppendLine("                {");
        sb.AppendLine("                    foreach (var child in GatherPossibleChildren(node))");
        sb.AppendLine("                    {");
        sb.AppendLine("                        queue.Add(child);");
        sb.AppendLine("                        parents.Add(node);");
        sb.AppendLine("                    }");
        sb.AppendLine("                }");
        sb.AppendLine("            }");
        sb.AppendLine("        }");
        sb.AppendLine();
        sb.AppendLine("        return null;");
        sb.AppendLine("    }");
        sb.AppendLine();
        sb.AppendLine("    /// <summary>");
        sb.AppendLine("    /// The children of <paramref name=\"node\"/> as work items — nodes and arrays mixed. TS prepends each one");
        sb.AppendLine("    /// (<c>unshift</c>) so that the walk's <c>pop</c> restores the source order.");
        sb.AppendLine("    /// </summary>");
        sb.AppendLine("    private static List<object> GatherPossibleChildren(Node node)");
        sb.AppendLine("    {");
        sb.AppendLine("        var children = new List<object>();");
        sb.AppendLine("        ForEachChild(node, AddNode, AddNodes);");
        sb.AppendLine("        return children;");
        sb.AppendLine();
        sb.AppendLine("        // Both callbacks return null (TS returns undefined), so the chain always reaches every child.");
        sb.AppendLine("        object? AddNode(Node child)");
        sb.AppendLine("        {");
        sb.AppendLine("            children.Insert(0, child);");
        sb.AppendLine("            return null;");
        sb.AppendLine("        }");
        sb.AppendLine();
        sb.AppendLine("        object? AddNodes(INodeArray<INode> nodes)");
        sb.AppendLine("        {");
        sb.AppendLine("            children.Insert(0, nodes);");
        sb.AppendLine("            return null;");
        sb.AppendLine("        }");
        sb.AppendLine("    }");
        sb.AppendLine();
        sb.AppendLine("    /// <summary>One child: TS's <c>visitNode(cbNode, node)</c> — skip when the member is missing, else call.</summary>");
        sb.AppendLine("    /// <remarks>");
        sb.AppendLine("    /// PORT-NOTE: the guard is <c>node is null</c> rather than <c>Js.IsTruthy(node)</c>; for a reference type");
        sb.AppendLine("    /// the two answer the same question, and only the pattern tells the compiler that the cast below is safe.");
        sb.AppendLine("    /// </remarks>");
        sb.AppendLine("    private static T? VisitNode<T>(INode? node, Func<Node, T?> cbNode)");
        sb.AppendLine("        => node is null ? default : cbNode((Node)node);");
        sb.AppendLine();
        sb.AppendLine("    /// <summary>An embedded array: TS's <c>visitNodes(cbNode, cbNodes, nodes)</c>.</summary>");
        sb.AppendLine("    /// <remarks>");
        sb.AppendLine("    /// With a <paramref name=\"cbNodes\"/> the array itself is handed over — no copy, no flattening. Without");
        sb.AppendLine("    /// one the elements are visited with <paramref name=\"cbNode\"/> until a truthy result appears, which is the");
        sb.AppendLine("    /// fallback <c>gatherPossibleChildren</c> depends on (it passes the same callback in both positions).");
        sb.AppendLine("    /// PORT-NOTE: again <c>nodes is null</c> rather than <c>Js.IsTruthy(nodes)</c> — same answer, but it narrows.");
        sb.AppendLine("    /// </remarks>");
        sb.AppendLine("    private static T? VisitNodes<T>(INodeArray<INode>? nodes, Func<Node, T?> cbNode, Func<INodeArray<INode>, T?>? cbNodes)");
        sb.AppendLine("    {");
        sb.AppendLine("        if (nodes is null) return default;");
        sb.AppendLine("        if (cbNodes is not null) return cbNodes(nodes);");
        sb.AppendLine("        foreach (var node in nodes)");
        sb.AppendLine("        {");
        sb.AppendLine("            var result = cbNode((Node)node);");
        sb.AppendLine("            if (Js.IsTruthy(result)) return result;");
        sb.AppendLine("        }");
        sb.AppendLine();
        sb.AppendLine("        return default;");
        sb.AppendLine("    }");
        sb.AppendLine();
        sb.AppendLine("    /// <summary>");
        sb.AppendLine("    /// An array visited element-wise, never through <c>cbNodes</c>: core.ts's <c>forEach(array, cbNode)</c>,");
        sb.AppendLine("    /// which two JSDoc visitors use instead of <c>visitNodes</c>.");
        sb.AppendLine("    /// </summary>");
        sb.AppendLine("    private static T? VisitElements<T>(IEnumerable<INode>? items, Func<Node, T?> cbNode)");
        sb.AppendLine("    {");
        sb.AppendLine("        if (items is null) return default;");
        sb.AppendLine("        foreach (var item in items)");
        sb.AppendLine("        {");
        sb.AppendLine("            var result = cbNode((Node)item);");
        sb.AppendLine("            if (Js.IsTruthy(result)) return result;");
        sb.AppendLine("        }");
        sb.AppendLine();
        sb.AppendLine("        return default;");
        sb.AppendLine("    }");
        sb.AppendLine();
        sb.AppendLine("    private sealed class SkipMarker");
        sb.AppendLine("    {");
        sb.AppendLine("        private SkipMarker()");
        sb.AppendLine("        {");
        sb.AppendLine("        }");
        sb.AppendLine();
        sb.AppendLine("        public static readonly SkipMarker Instance = new();");
        sb.AppendLine("    }");
        sb.AppendLine();
    }

    /// <summary>Emits one kind's private visitor.</summary>
    private static void AppendVisitor(
        StringBuilder sb,
        TsTypeModel typeModel,
        TsTypeMapper mapper,
        TsForEachChildEntry entry,
        TsInterface nodeClass,
        string className,
        List<(string Kind, string Member, string Reason)> dropped)
    {
        var tsVisitor = entry.Visitor ?? $"forEachChildIn{entry.Kind}";
        sb.AppendLine($"    /// <summary>Child visitor for <see cref=\"SyntaxKind.{entry.Kind}\"/> — TS's <c>{tsVisitor}</c> over <c>{Escape(entry.NodeType)}</c>.</summary>");
        sb.AppendLine($"    // ported from: {SourcePath}:{entry.Line}" + (entry.Visitor is null ? "" : $" (forEachChildIn{entry.Kind} → {entry.Visitor})"));
        sb.AppendLine($"    private static T? ForEachChildIn{entry.Kind}<T>(Node node, Func<Node, T?> cbNode, Func<INodeArray<INode>, T?>? cbNodes)");
        sb.AppendLine("    {");
        sb.AppendLine($"        var n = ({className})node;");
        sb.AppendLine();

        foreach (var visit in entry.Visits)
        {
            AppendVisit(sb, typeModel, mapper, entry, nodeClass, visit, "        ", dropped);
        }

        sb.AppendLine("        return default;");
        sb.AppendLine("    }");
        sb.AppendLine();
    }

    private static void AppendVisit(
        StringBuilder sb,
        TsTypeModel typeModel,
        TsTypeMapper mapper,
        TsForEachChildEntry entry,
        TsInterface nodeClass,
        TsForEachChildVisit visit,
        string indent,
        List<(string Kind, string Member, string Reason)> dropped)
    {
        // A conditional's two arms carry the members; the condition names its own. Handle it before the
        // member-based forms below.
        if (visit.Form == "if")
        {
            AppendConditional(sb, typeModel, mapper, entry, nodeClass, visit, indent, dropped);
            return;
        }

        if (visit.Member is null)
        {
            throw new InvalidOperationException($"forEachChild: SyntaxKind.{entry.Kind} has a visit without a member (parser.ts:{visit.Line})");
        }

        var found = FindMember(typeModel, nodeClass, visit.Member);
        if (found is null || IsSkipped(visit.Member))
        {
            // TS writes `(node as X).member` exactly when the union's other members do not have the member; for
            // them the read is undefined and visitNode/visitNodes skip. The port's class has no member there, so
            // the step is omitted — but only when TS said so with a cast. Anything else is a table entry the port
            // would silently lose, which must fail loudly instead.
            if (visit.Cast is not null)
            {
                dropped.Add((entry.Kind, visit.Member, $"the concrete class has no member (TS reads `({visit.Cast}).{visit.Member}` as undefined)"));
                sb.AppendLine($"{indent}// parser.ts:{visit.Line}: `({visit.Cast})node.{visit.Member}` is undefined for this kind, so the step is absent.");
                return;
            }

            throw new InvalidOperationException(
                $"forEachChild: {nodeClass.Name}.{visit.Member} (parser.ts:{visit.Line}) has no member to visit");
        }

        var (memberName, memberType, memberOptional) = found.Value;
        var mapped = mapper.MapMember(memberType, memberOptional).Trim();

        // `undefined` / `never` members (§12.6) can never hold a child, so TS's read is always undefined and the
        // step is a no-op. `FunctionTypeNode.modifiers` is the case in the table: TS narrows it to `undefined`
        // because a function *type* has no modifiers.
        if (mapped is "JsUndefined?" or "JsUndefined" or "JsNever?" or "JsNever")
        {
            dropped.Add((entry.Kind, memberName, $"declared '{memberType}' (mapped '{mapped}'), so there is never a child to visit"));
            sb.AppendLine($"{indent}// parser.ts:{visit.Line}: `node.{memberName}` is declared `{memberType}`, so the step can never visit anything.");
            return;
        }

        switch (visit.Form)
        {
            case "node":
            {
                RequireNodeType(typeModel, entry, visit, memberName, memberType, mapped);
                sb.AppendLine($"{indent}{{");
                sb.AppendLine($"{indent}    var result = VisitNode(n.{PascalCase(visit.Member)}, cbNode);");
                sb.AppendLine($"{indent}    if (Js.IsTruthy(result)) return result;");
                sb.AppendLine($"{indent}}}");
                break;
            }

            case "nodes" when visit.Guard == "notNull":
            {
                RequireNodeArray(typeModel, entry, visit, memberName, memberType, mapped);
                sb.AppendLine($"{indent}{{");
                sb.AppendLine($"{indent}    var result = VisitNodes(n.{PascalCase(visit.Member)}, cbNode, cbNodes);");
                sb.AppendLine($"{indent}    if (Js.IsTruthy(result)) return result;");
                sb.AppendLine($"{indent}}}");
                break;
            }

            case "nodes" when visit.Guard == "notString":
            {
                // `typeof node.member === "string" ? undefined : visitNodes(cbNode, cbNodes, node.member)`: the member
                // is `string | NodeArray<…>`, so only the array half is visited. The pattern is the covariant view
                // rather than the member's exact array type: the property is `object?` (a string shares the slot), so
                // matching `INodeArray<INode>` accepts whichever node array the parser stores, and a string never
                // matches.
                RequireStringGuardedArray(typeModel, entry, visit, memberName, memberType, mapper);
                sb.AppendLine($"{indent}if (n.{PascalCase(visit.Member)} is INodeArray<INode> {CamelCase(visit.Member)}Nodes)");
                sb.AppendLine($"{indent}{{");
                sb.AppendLine($"{indent}    var result = VisitNodes({CamelCase(visit.Member)}Nodes, cbNode, cbNodes);");
                sb.AppendLine($"{indent}    if (Js.IsTruthy(result)) return result;");
                sb.AppendLine($"{indent}}}");
                break;
            }

            case "elements":
            {
                RequireEnumerable(typeModel, entry, visit, memberName, memberType, mapped);
                sb.AppendLine($"{indent}{{");
                sb.AppendLine($"{indent}    var result = VisitElements(n.{PascalCase(visit.Member)}, cbNode);");
                sb.AppendLine($"{indent}    if (Js.IsTruthy(result)) return result;");
                sb.AppendLine($"{indent}}}");
                break;
            }

            default:
                throw new InvalidOperationException(
                    $"forEachChild: unsupported visit form '{visit.Form}' for SyntaxKind.{entry.Kind} (parser.ts:{visit.Line})");
        }
    }

    private static void AppendConditional(
        StringBuilder sb,
        TsTypeModel typeModel,
        TsTypeMapper mapper,
        TsForEachChildEntry entry,
        TsInterface nodeClass,
        TsForEachChildVisit visit,
        string indent,
        List<(string Kind, string Member, string Reason)> dropped)
    {
        var condition = visit.Condition
            ?? throw new InvalidOperationException($"forEachChild: SyntaxKind.{entry.Kind} has an if without a condition (parser.ts:{visit.Line})");

        var conditionFound = FindMember(typeModel, nodeClass, condition.Member)
            ?? throw new InvalidOperationException($"forEachChild: {nodeClass.Name}.{condition.Member} (parser.ts:{visit.Line}) has no member to test");
        var (_, conditionType, conditionOptional) = conditionFound;
        var conditionMapped = mapper.MapMember(conditionType, conditionOptional).Trim();

        var test = condition.Form switch
        {
            "member" when conditionMapped.TrimEnd('?') == "bool" => $"Js.IsTruthy(n.{PascalCase(condition.Member)})",
            "member" => throw new InvalidOperationException(
                $"forEachChild: {nodeClass.Name}.{condition.Member} is '{conditionType}' (mapped '{conditionMapped}'), not a bool (parser.ts:{visit.Line})"),
            // `node.member && node.member.kind === SyntaxKind.X`: `?.` keeps the null case falsy.
            "kindIs" => Operand(typeModel, entry, visit, condition.Member, conditionType, conditionMapped, condition.Kind!),
            _ => throw new InvalidOperationException(
                $"forEachChild: unsupported condition form '{condition.Form}' for SyntaxKind.{entry.Kind} (parser.ts:{visit.Line})"),
        };

        sb.AppendLine($"{indent}if ({test})");
        sb.AppendLine($"{indent}{{");
        foreach (var whenTrue in visit.WhenTrue)
        {
            AppendVisit(sb, typeModel, mapper, entry, nodeClass, whenTrue, indent + "    ", dropped);
        }

        sb.AppendLine($"{indent}}}");
        sb.AppendLine($"{indent}else");
        sb.AppendLine($"{indent}{{");
        foreach (var whenFalse in visit.WhenFalse)
        {
            AppendVisit(sb, typeModel, mapper, entry, nodeClass, whenFalse, indent + "    ", dropped);
        }

        sb.AppendLine($"{indent}}}");
    }

    private static string Operand(
        TsTypeModel typeModel,
        TsForEachChildEntry entry,
        TsForEachChildVisit visit,
        string memberName,
        string memberType,
        string mapped,
        string kind)
    {
        RequireNodeType(typeModel, entry, visit, memberName, memberType, mapped);
        return $"n.{PascalCase(memberName)}?.Kind == SyntaxKind.{kind}";
    }

    /// <summary>
    /// Checks that the non-string half of a <c>typeof member === "string"</c> guard is a node array. The emitted
    /// pattern is the covariant <c>INodeArray&lt;INode&gt;</c>, but a guard over anything else would mean the table
    /// visits something the port cannot pass to the array callback.
    /// </summary>
    private static void RequireStringGuardedArray(
        TsTypeModel typeModel,
        TsForEachChildEntry entry,
        TsForEachChildVisit visit,
        string memberName,
        string memberType,
        TsTypeMapper mapper)
    {
        var parts = TsTypeMapper.SplitTopLevel(memberType, '|')
            .Select(static part => part.Trim())
            .Where(static part => part is not ("" or "string" or "undefined" or "null" or "void" or "never"))
            .ToList();

        if (parts.Count != 1)
        {
            throw new InvalidOperationException(
                $"forEachChild: {memberName} is '{memberType}' (parser.ts:{visit.Line}); expected one non-string array half");
        }

        var mapped = mapper.MapMember(parts[0], optional: false).Trim();
        if (!TryGenericArgument(mapped, "NodeArray", out var element))
        {
            throw new InvalidOperationException(
                $"forEachChild: {memberName} is '{memberType}' (mapped '{mapped}'), not a NodeArray (parser.ts:{visit.Line})");
        }

        RequireNodeElement(typeModel, entry, visit, memberName, memberType, element);
    }

    private static void RequireNodeType(
        TsTypeModel typeModel, TsForEachChildEntry entry, TsForEachChildVisit visit, string memberName, string memberType, string mapped)
    {
        if (!IsNodeType(typeModel, mapped))
        {
            throw new InvalidOperationException(
                $"forEachChild: {memberName} on SyntaxKind.{entry.Kind} is '{memberType}' (mapped '{mapped}'), which is not a node type (parser.ts:{visit.Line})");
        }
    }

    private static void RequireNodeArray(
        TsTypeModel typeModel, TsForEachChildEntry entry, TsForEachChildVisit visit, string memberName, string memberType, string mapped)
    {
        if (!TryGenericArgument(mapped, "NodeArray", out var element))
        {
            throw new InvalidOperationException(
                $"forEachChild: {memberName} on SyntaxKind.{entry.Kind} is '{memberType}' (mapped '{mapped}'), not a NodeArray (parser.ts:{visit.Line})");
        }

        RequireNodeElement(typeModel, entry, visit, memberName, memberType, element);
    }

    private static void RequireEnumerable(
        TsTypeModel typeModel, TsForEachChildEntry entry, TsForEachChildVisit visit, string memberName, string memberType, string mapped)
    {
        if (!TryGenericArgument(mapped, "List", out var element) && !TryGenericArgument(mapped, "NodeArray", out element))
        {
            throw new InvalidOperationException(
                $"forEachChild: {memberName} on SyntaxKind.{entry.Kind} is '{memberType}' (mapped '{mapped}'), not enumerable (parser.ts:{visit.Line})");
        }

        RequireNodeElement(typeModel, entry, visit, memberName, memberType, element);
    }

    private static void RequireNodeElement(
        TsTypeModel typeModel, TsForEachChildEntry entry, TsForEachChildVisit visit, string memberName, string memberType, string element)
    {
        if (!IsNodeType(typeModel, element))
        {
            throw new InvalidOperationException(
                $"forEachChild: {memberName} on SyntaxKind.{entry.Kind} has element type '{element}' ({memberType}), which does not convert to INode (parser.ts:{visit.Line})");
        }
    }

    private static bool IsNodeType(TsTypeModel typeModel, string csharpType)
    {
        var bare = TsTypeMapper.BareName(csharpType.TrimEnd('?').Trim());
        if (bare is "object" or "bool" or "int" or "string") return false;

        var tsName = typeModel.TsNameOf(bare);
        return tsName is not null && (tsName == "Node" || typeModel.ReachesNode(tsName));
    }

    private static bool TryGenericArgument(string csharpType, string genericName, out string argument)
    {
        var text = csharpType.TrimEnd('?').Trim();
        var prefix = genericName + "<";
        if (text.StartsWith(prefix, StringComparison.Ordinal) && text.EndsWith('>'))
        {
            argument = text[prefix.Length..^1];
            return true;
        }

        argument = "";
        return false;
    }

    /// <summary>
    /// The member declaration the concrete class exposes, found the same way the class emitter finds it: the
    /// type's own member first, then its base chain (a class narrows a member by redeclaring it).
    /// </summary>
    /// <remarks>
    /// A base may be generic — <c>ObjectLiteralExpression : ObjectLiteralExpressionBase&lt;Node&gt;</c> — and its
    /// member types are written in terms of its type parameters (<c>Properties: NodeArray&lt;T&gt;</c>), so the
    /// arguments are substituted on the way down. Without that, <c>Properties</c> would map to
    /// <c>NodeArray&lt;object?&gt;</c> and the emitted code would not convert to the array callback.
    /// </remarks>
    private static (string Name, string Type, bool IsOptional)? FindMember(TsTypeModel typeModel, TsInterface nodeClass, string name)
    {
        var seen = new HashSet<string>(StringComparer.Ordinal);
        return Find(nodeClass.Name, substitutions: null);

        (string Name, string Type, bool IsOptional)? Find(string current, Dictionary<string, string>? substitutions)
        {
            if (!seen.Add(current) || !typeModel.Interfaces.TryGetValue(current, out var iface)) return null;

            foreach (var candidate in iface.Members)
            {
                if (candidate.Name != name) continue;
                var type = substitutions is null ? candidate.Type : Substitute(candidate.Type, substitutions);
                return (candidate.Name, type, candidate.IsOptional);
            }

            foreach (var baseReference in iface.Extends)
            {
                var bare = TsTypeMapper.BareName(baseReference);
                var arguments = TypeArguments(baseReference);

                Dictionary<string, string>? next = null;
                if (arguments.Count != 0
                    && typeModel.Interfaces.TryGetValue(bare, out var baseInterface)
                    && baseInterface.TypeParameters.Count == arguments.Count)
                {
                    next = new Dictionary<string, string>(StringComparer.Ordinal);
                    for (var i = 0; i < arguments.Count; i++)
                    {
                        next[baseInterface.TypeParameters[i]] = substitutions is null
                            ? arguments[i]
                            : Substitute(arguments[i], substitutions);
                    }
                }

                var found = Find(bare, next);
                if (found is not null) return found;
            }

            return null;
        }
    }

    /// <summary>The type arguments of a reference such as <c>ObjectLiteralExpressionBase&lt;Node&gt;</c>.</summary>
    private static List<string> TypeArguments(string typeReference)
    {
        var start = typeReference.IndexOf('<');
        if (start < 0 || !typeReference.EndsWith('>')) return [];

        return TsTypeMapper.SplitTopLevel(typeReference[(start + 1)..^1], ',')
            .Select(static argument => argument.Trim())
            .Where(static argument => argument.Length != 0)
            .ToList();
    }

    private static string Substitute(string type, Dictionary<string, string> substitutions)
    {
        foreach (var (name, value) in substitutions)
        {
            type = Regex.Replace(type, $@"(?<![\w]){Regex.Escape(name)}(?![\w])", value.Replace("$", "$$"));
        }

        return type;
    }

    /// <summary>Members the generated classes do not declare (they live on the hand-written <c>Node</c> base).</summary>
    private static bool IsSkipped(string name)
        => name.StartsWith('_') || name == "kind" || s_nodeMembers.Contains(name);

    /// <summary>Whether <paramref name="ancestor"/> is on <paramref name="descendant"/>'s class chain.</summary>
    private static bool IsAncestor(TsTypeModel typeModel, string ancestor, string descendant)
        => !ReferenceEquals(ancestor, descendant) && typeModel.ClassChainOf(descendant).Contains(ancestor, StringComparer.Ordinal);

    private static string PascalCase(string name) => name.Length == 0 ? name : char.ToUpperInvariant(name[0]) + name[1..];

    /// <summary>Escapes a TS type for an XML doc comment (<c>NodeArray&lt;X&gt;</c>, unions and intersections).</summary>
    private static string Escape(string text)
        => text.Replace("&", "&amp;").Replace("<", "&lt;").Replace(">", "&gt;");

    private static string CamelCase(string name) => name.Length == 0 ? name : char.ToLowerInvariant(name[0]) + name[1..];
}
