using System.Text;
using System.Text.Json;

namespace TypeScript.Compiler.Tools;

/// <summary>
/// Generates <c>Lexer/ScannerTables.cs</c> from the data tables lifted out of <c>scanner.ts</c>.
/// </summary>
/// <remarks>
/// The scanner reads four Unicode range tables (4,454 endpoints), the keyword and token tables, the
/// regular-expression flag tables and the Unicode property tables. They are literals in the TS source, and the
/// extractor evaluates them there; this emitter turns the resulting JSON into C#.
/// <para>
/// A table entry that names an exported enum member arrives as <c>{ "@ref": … }</c> and is emitted as that
/// reference — the numbers live in the generated enums, so spelling them out again here would be a second
/// source of truth.
/// </para>
/// </remarks>
internal static class ScannerTablesEmitter
{
    /// <summary>How many numbers go on one line of the Unicode range tables.</summary>
    private const int NumbersPerLine = 10;

    public static GeneratedFile Emit(TsModel model, string outputRoot)
    {
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated>");
        sb.AppendLine("//   Generated from src/compiler/scanner.ts (plus src/compiler/types.ts) by tools/Gen — DO NOT EDIT.");
        sb.AppendLine("//   Regenerate with:");
        sb.AppendLine("//     dotnet run --project tools/Gen -- --out src/TypeScript.Compiler");
        sb.AppendLine("// </auto-generated>");
        sb.AppendLine();
        // Roslyn does not apply the project's nullable context to files marked <auto-generated>.
        sb.AppendLine("#nullable enable");
        sb.AppendLine();
        sb.AppendLine("namespace TypeScript.Compiler;");
        sb.AppendLine();
        sb.AppendLine("/// <summary>");
        sb.AppendLine("/// The scanner's data tables: keyword and token spellings, regular-expression flags, the Unicode");
        sb.AppendLine("/// identifier ranges and the Unicode property tables.");
        sb.AppendLine("/// </summary>");
        sb.AppendLine("/// <remarks>");
        sb.AppendLine("/// PORT-NOTE: the Unicode range tables are pairs of inclusive code point bounds, exactly as TS writes");
        sb.AppendLine("/// them; <c>UnicodeES5*</c> is used below ES2015 and <c>UnicodeESNext*</c> from ES2015 on.");
        sb.AppendLine("/// </remarks>");
        sb.AppendLine("internal static partial class ScannerTables");
        sb.AppendLine("{");

        var keywordTable = Table(model, "textToKeywordObj");

        // Keyword text → token kind. The object's insertion order is the source order.
        sb.AppendLine(Comment(keywordTable, "textToKeywordObj"));
        sb.AppendLine("    /// <summary>The reserved words, in source order.</summary>");
        sb.AppendLine("    public static readonly IList<(string Text, SyntaxKind Kind)> TextToKeyword =");
        sb.AppendLine("    [");
        foreach (var property in keywordTable.Value.EnumerateObject())
        {
            sb.AppendLine($"        ({TsStringLiteral.ToCSharp(property.Name)}, {Member(property.Value)}),");
        }

        sb.AppendLine("    ];");
        sb.AppendLine();

        // Token text → token kind, keywords first, then the punctuators.
        var tokenTable = Table(model, "textToToken");
        sb.AppendLine(Comment(tokenTable, "textToToken"));
        sb.AppendLine("    /// <summary>The keywords followed by the punctuators — every multi-character token spelling.</summary>");
        sb.AppendLine("    public static readonly IList<(string Text, SyntaxKind Kind)> TextToToken =");
        sb.AppendLine("    [");
        foreach (var entry in tokenTable.Value.EnumerateArray())
        {
            var pair = entry.EnumerateArray().ToList();
            sb.AppendLine($"        ({TsStringLiteral.ToCSharp(pair[0].GetString()!)}, {Member(pair[1])}),");
        }

        sb.AppendLine("    ];");
        sb.AppendLine();

        // Regular-expression flag character → flag.
        sb.AppendLine(Comment(Table(model, "charCodeToRegExpFlag"), "charCodeToRegExpFlag"));
        sb.AppendLine("    /// <summary>The character that spells a regular-expression flag.</summary>");
        sb.AppendLine("    public static readonly IList<(int CharCode, RegularExpressionFlags Flag)> CharCodeToRegExpFlag =");
        sb.AppendLine("    [");
        foreach (var entry in Table(model, "charCodeToRegExpFlag").Value.EnumerateArray())
        {
            var pair = entry.EnumerateArray().ToList();
            sb.AppendLine($"        ({Member(pair[0])}, {Member(pair[1])}),");
        }

        sb.AppendLine("    ];");
        sb.AppendLine();

        // Regular-expression flag → the target it needs. TS looks the target up through
        // LanguageFeatureMinimumTarget, a table in types.ts that nothing else needs, so it is resolved here.
        sb.AppendLine(Comment(Table(model, "regExpFlagToFirstAvailableLanguageVersion"), "regExpFlagToFirstAvailableLanguageVersion"));
        sb.AppendLine("    /// <summary>The earliest target a regular-expression flag can be used with.</summary>");
        sb.AppendLine("    public static readonly IList<(RegularExpressionFlags Flag, ScriptTarget Target)> RegExpFlagToFirstAvailableTarget =");
        sb.AppendLine("    [");
        var features = Table(model, "LanguageFeatureMinimumTarget").Value;
        foreach (var entry in Table(model, "regExpFlagToFirstAvailableLanguageVersion").Value.EnumerateArray())
        {
            var pair = entry.EnumerateArray().ToList();
            sb.AppendLine($"        ({Member(pair[0])}, {Member(ResolveFeature(pair[1], features))}),");
        }

        sb.AppendLine("    ];");
        sb.AppendLine();

        AppendNumberTable(sb, model, "unicodeES5IdentifierStart",
            "Inclusive code point bounds of ES5 identifier starts (scanner.ts:331).", "UnicodeES5IdentifierStart");
        AppendNumberTable(sb, model, "unicodeES5IdentifierPart",
            "Inclusive code point bounds of ES5 identifier parts (scanner.ts:333).", "UnicodeES5IdentifierPart");
        AppendNumberTable(sb, model, "unicodeESNextIdentifierStart",
            "Inclusive code point bounds of ES2015+ identifier starts (scanner.ts:342).", "UnicodeESNextIdentifierStart");
        AppendNumberTable(sb, model, "unicodeESNextIdentifierPart",
            "Inclusive code point bounds of ES2015+ identifier parts (scanner.ts:344).", "UnicodeESNextIdentifierPart");

        // Unicode property name tables, used to validate `\p{…}` in a `u`/`v` regular expression.
        sb.AppendLine(Comment(Table(model, "nonBinaryUnicodeProperties"), "nonBinaryUnicodeProperties"));
        sb.AppendLine("    /// <summary>Non-binary Unicode property aliases → their canonical names.</summary>");
        sb.AppendLine("    public static readonly IList<(string Alias, string CanonicalName)> NonBinaryUnicodeProperties =");
        sb.AppendLine("    [");
        foreach (var entry in Table(model, "nonBinaryUnicodeProperties").Value.EnumerateArray())
        {
            var pair = entry.EnumerateArray().ToList();
            sb.AppendLine($"        ({TsStringLiteral.ToCSharp(pair[0].GetString()!)}, {TsStringLiteral.ToCSharp(pair[1].GetString()!)}),");
        }

        sb.AppendLine("    ];");
        sb.AppendLine();

        AppendStringTable(sb, model, "binaryUnicodeProperties", "Binary Unicode property names (scanner.ts:4085).", "BinaryUnicodeProperties");
        AppendStringTable(sb, model, "binaryUnicodePropertiesOfStrings", "Binary Unicode properties of strings (scanner.ts:4090).", "BinaryUnicodePropertiesOfStrings");

        sb.AppendLine(Comment(Table(model, "valuesOfNonBinaryUnicodeProperties"), "valuesOfNonBinaryUnicodeProperties"));
        sb.AppendLine("    /// <summary>The value of each non-binary Unicode property.</summary>");
        sb.AppendLine("    public static readonly IList<(string Property, IList<string> Values)> ValuesOfNonBinaryUnicodeProperties =");
        sb.AppendLine("    [");
        foreach (var property in Table(model, "valuesOfNonBinaryUnicodeProperties").Value.EnumerateObject())
        {
            var values = string.Join(", ", property.Value.EnumerateArray().Select(static v => TsStringLiteral.ToCSharp(v.GetString()!)));
            sb.AppendLine($"        ({TsStringLiteral.ToCSharp(property.Name)}, [{values}]),");
        }

        sb.AppendLine("    ];");
        sb.AppendLine("}");

        // The repository is LF-only (.gitattributes: eol=lf); AppendLine emits CRLF on Windows.
        return new GeneratedFile($"{outputRoot}/Lexer/ScannerTables.cs", sb.ToString().Replace("\r\n", "\n"));
    }

    private static void AppendNumberTable(StringBuilder sb, TsModel model, string tableName, string summary, string csharpName)
    {
        var table = Table(model, tableName);
        sb.AppendLine(Comment(table, tableName));
        sb.AppendLine($"    /// <summary>{summary}</summary>");
        sb.AppendLine($"    public static readonly IList<int> {csharpName} =");
        sb.AppendLine("    [");

        var numbers = table.Value.EnumerateArray().Select(static e => e.GetInt32()).ToList();
        for (var i = 0; i < numbers.Count; i += NumbersPerLine)
        {
            var line = string.Join(", ", numbers.Skip(i).Take(NumbersPerLine));
            sb.AppendLine($"        {line},");
        }

        sb.AppendLine("    ];");
        sb.AppendLine();
    }

    private static void AppendStringTable(StringBuilder sb, TsModel model, string tableName, string summary, string csharpName)
    {
        var table = Table(model, tableName);
        sb.AppendLine(Comment(table, tableName));
        sb.AppendLine($"    /// <summary>{summary}</summary>");
        sb.AppendLine($"    public static readonly IList<string> {csharpName} =");
        sb.AppendLine("    [");
        foreach (var element in table.Value.EnumerateArray())
        {
            sb.AppendLine($"        {TsStringLiteral.ToCSharp(element.GetString()!)},");
        }

        sb.AppendLine("    ];");
        sb.AppendLine();
    }

    private static TsTable Table(TsModel model, string name)
        => model.Tables.FirstOrDefault(table => table.Name == name)
            ?? throw new InvalidOperationException($"the extractor did not produce the '{name}' table");

    /// <summary>The provenance comment above a generated table.</summary>
    private static string Comment(TsTable table, string tsName)
        => $"    // ported from: {table.Source}:{table.StartLine} — TS: `{tsName}`.";

    /// <summary>Reads an <c>{ "@ref": … }</c> entry back into the member reference it stands for.</summary>
    private static string Member(JsonElement element)
    {
        if (element.ValueKind == JsonValueKind.Object && element.TryGetProperty("@ref", out var reference))
        {
            return reference.GetString()!;
        }

        throw new InvalidOperationException($"expected an enum reference, found {element}");
    }

    /// <summary>
    /// Resolves <c>LanguageFeatureMinimumTarget.X</c> to the target it stands for.
    /// </summary>
    /// <remarks>
    /// TS reads the minimum target out of <c>LanguageFeatureMinimumTarget</c>, a table in <c>types.ts</c> that
    /// nothing else in the port needs. Rather than generate a table no one reads, the reference is resolved here
    /// and only the resolved <see cref="ScriptTarget"/> is emitted.
    /// </remarks>
    private static JsonElement ResolveFeature(JsonElement element, JsonElement features)
    {
        const string prefix = "LanguageFeatureMinimumTarget.";
        var reference = Member(element);
        if (!reference.StartsWith(prefix, StringComparison.Ordinal))
        {
            throw new InvalidOperationException($"expected a LanguageFeatureMinimumTarget reference, found '{reference}'");
        }

        var feature = reference[prefix.Length..];
        if (!features.TryGetProperty(feature, out var target))
        {
            throw new InvalidOperationException($"LanguageFeatureMinimumTarget has no '{feature}'");
        }

        return target;
    }
}
