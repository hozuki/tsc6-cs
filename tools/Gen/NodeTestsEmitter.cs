using System.Text;

namespace TypeScript.Compiler.Tools;

/// <summary>
/// Generates <c>Parser/NodeTests.cs</c> — the node predicates of <c>factory/nodeTests.ts</c>.
/// </summary>
/// <remarks>
/// All 227 of those functions are a single <c>return node.kind === SyntaxKind.X;</c>, so the file is a table rather
/// than code and is generated like the other tables (see the extractor's <c>collectPredicates</c>, which refuses
/// any other body shape).
/// <para>
/// The port keeps the <c>kind</c> comparison instead of emitting <c>node is NumericLiteral</c>: several predicates
/// test a kind whose C# shape is shared with others (<c>isExportModifier</c> tests <c>ExportKeyword</c>, and the
/// port has one <c>KeywordToken</c> class for all keywords), so a type test would not be equivalent.
/// </para>
/// </remarks>
internal static class NodeTestsEmitter
{
    /// <summary>The source the table is derived from, relative to the TypeScript checkout.</summary>
    public const string SourcePath = "src/compiler/factory/nodeTests.ts";

    public static GeneratedFile Emit(TsModel model, string outputRoot)
    {
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated>");
        sb.AppendLine($"//   Generated from {SourcePath} by tools/Gen — DO NOT EDIT.");
        sb.AppendLine("//   Regenerate with:");
        sb.AppendLine("//     dotnet run --project tools/Gen -- --out src/TypeScript.Compiler");
        sb.AppendLine("// </auto-generated>");
        sb.AppendLine();
        // Roslyn does not apply the project's nullable context to files marked <auto-generated>.
        sb.AppendLine("#nullable enable");
        sb.AppendLine();
        sb.AppendLine("namespace TypeScript.Compiler;");
        sb.AppendLine();
        sb.AppendLine("/// <summary>");
        sb.AppendLine("/// Node kind predicates — one per <c>factory/nodeTests.ts</c> export.");
        sb.AppendLine("/// </summary>");
        sb.AppendLine("/// <remarks>");
        sb.AppendLine("/// PORT-NOTE: these compare <see cref=\"Node.Kind\"/> rather than typing the node, because several of them");
        sb.AppendLine("/// test a kind that shares its C# class with others (all keywords are <c>KeywordToken</c>).");
        sb.AppendLine("/// </remarks>");
        sb.AppendLine("internal static partial class NodeTests");
        sb.AppendLine("{");

        foreach (var predicate in model.Predicates)
        {
            sb.AppendLine($"    // ported from: {SourcePath}:{predicate.StartLine}");
            var test = string.Join(" || ", predicate.Kinds.Select(kind => $"node.Kind == SyntaxKind.{kind}"));
            sb.AppendLine($"    public static bool {Pascal(predicate.Name)}(Node node) => {test};");
        }

        sb.AppendLine("}");

        // The repository is LF-only (.gitattributes: eol=lf); AppendLine emits CRLF on Windows.
        return new GeneratedFile($"{outputRoot}/Parser/NodeTests.cs", sb.ToString().Replace("\r\n", "\n"));
    }

    /// <summary>TS's <c>isNumericLiteral</c> becomes <c>IsNumericLiteral</c>.</summary>
    private static string Pascal(string name) => char.ToUpperInvariant(name[0]) + name[1..];
}
