using System.Text;

namespace TypeScript.Compiler.Tools;

internal sealed record EnumSpec(
    /// <summary>Enum name, identical in TS and C#.</summary>
    string Name,
    /// <summary>TS source file relative to the TS repo root.</summary>
    string TsRelativePath,
    /// <summary>
    /// C# underlying type (<c>int</c>/<c>uint</c>/<c>ulong</c>) for numeric enums,
    /// or <c>null</c> when the TS enum is string-valued and becomes a constants class.
    /// </summary>
    string? UnderlyingType,
    /// <summary>Whether to apply <c>[Flags]</c>. Only meaningful for numeric enums.</summary>
    bool Flags,
    string Summary);

/// <summary>Renders a parsed <see cref="TsEnum"/> as C# source.</summary>
internal static class EnumEmitter
{
    public static string Emit(TsEnum tsEnum, EnumSpec spec)
        => spec.UnderlyingType is null ? EmitStringTable(tsEnum, spec) : EmitNumericEnum(tsEnum, spec);

    /// <summary>
    /// Numeric enum: <c>internal enum Name : T</c> with explicit values.
    /// </summary>
    private static string EmitNumericEnum(TsEnum tsEnum, EnumSpec spec)
    {
        var sb = Header(tsEnum, spec);
        if (spec.Flags) sb.AppendLine("[Flags]");
        sb.AppendLine($"internal enum {spec.Name} : {spec.UnderlyingType}");
        sb.AppendLine("{");

        foreach (var member in tsEnum.Members)
        {
            AppendDoc(sb, member);

            var literal = FormatNumericValue(member.Value, spec);
            var line = $"    {member.Name} = {literal},";

            var notes = new List<string>();
            if (member.IsAlias && member.ValueExpression is not null)
            {
                // Preserve the alias relationship, which the numeric value alone loses.
                notes.Add($"TS: {member.Name} = {member.ValueExpression}");
            }
            else if (member.ValueExpression is not null && member.ValueExpression != literal)
            {
                notes.Add($"TS: {member.ValueExpression}");
            }

            if (member.TrailingComment is { Length: > 0 }) notes.Add(member.TrailingComment);
            if (notes.Count != 0) line += "  // " + string.Join("  |  ", notes);

            sb.AppendLine(line);
        }

        sb.AppendLine("}");
        return Finish(sb);
    }

    /// <summary>
    /// String-valued enum: <c>internal static class Name</c> with <c>const string</c> members.
    /// </summary>
    /// <remarks>
    /// TS's string enums are consumed as plain strings at every call site (comparing
    /// <c>symbol.escapedName</c>, passing <c>Extension.Ts</c> where a <c>string</c> is expected, writing
    /// <c>ForegroundColorEscapeSequences.Red</c> straight to a stream). Modelling them as a C# enum would
    /// force a conversion at each of those sites and could not represent values like <c>"__call"</c> or
    /// <c>"export="</c>; constants keep the call sites identical to TS.
    /// </remarks>
    private static string EmitStringTable(TsEnum tsEnum, EnumSpec spec)
    {
        var sb = Header(tsEnum, spec);
        sb.AppendLine($"internal static class {spec.Name}");
        sb.AppendLine("{");

        foreach (var member in tsEnum.Members)
        {
            AppendDoc(sb, member);

            var line = $"    public const string {member.Name} = {TsStringLiteral.ToCSharp(member.StringValue!)};";
            if (member.TrailingComment is { Length: > 0 }) line += "  // " + member.TrailingComment;
            sb.AppendLine(line);
        }

        sb.AppendLine("}");
        return Finish(sb);
    }

    private static StringBuilder Header(TsEnum tsEnum, EnumSpec spec)
    {
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated>");
        sb.AppendLine($"//   Generated from {spec.TsRelativePath}:{tsEnum.StartLine}-{tsEnum.EndLine} by tools/Gen — DO NOT EDIT.");
        sb.AppendLine("//   Regenerate with:");
        sb.AppendLine("//     dotnet run --project tools/Gen -- --out src/TypeScript.Compiler");
        sb.AppendLine("// </auto-generated>");
        sb.AppendLine();
        sb.AppendLine("namespace TypeScript.Compiler;");
        sb.AppendLine();
        sb.AppendLine($"/// <summary>{spec.Summary}</summary>");
        return sb;
    }

    private static void AppendDoc(StringBuilder sb, TsEnumMember member)
    {
        if (member.Doc is { Length: > 0 })
        {
            sb.AppendLine($"    /// <summary>{Escape(member.Doc)}</summary>");
        }
    }

    private static string Finish(StringBuilder sb)
    {
        // The repository is LF-only (.gitattributes: eol=lf); AppendLine emits CRLF on Windows and would
        // make the committed files differ from what the generator produces after checkout.
        return sb.ToString().Replace("\r\n", "\n");
    }

    private static string FormatNumericValue(long value, EnumSpec spec)
    {
        if (value == 0) return "0";
        return spec.Flags ? $"0x{value:X8}" : value.ToString(System.Globalization.CultureInfo.InvariantCulture);
    }

    /// <summary>Escapes text for use inside an XML doc comment.</summary>
    private static string Escape(string text)
        => text.Replace("&", "&amp;").Replace("<", "&lt;").Replace(">", "&gt;");
}
