using System.Text.RegularExpressions;

namespace TypeScript.Compiler.Tests;

/// <summary>
/// Guards the contract that makes the hand-written half of a generated type possible.
/// </summary>
/// <remarks>
/// Every type the generator emits is declared <c>partial</c> so that members it cannot or should not produce can be
/// added by hand in a separate file — <c>Model/SyntaxList.cs</c> adds <c>SyntaxList._children</c> this way. The
/// generator could regress on this silently (the build stays green until someone needs the escape hatch), so the
/// declaration form is asserted here.
/// </remarks>
public class GeneratedPartialTests
{
    private static readonly string[] s_generatedFiles =
    [
        "Model/NodeClasses.cs",
        "Model/NodeInterfaces.cs",
        "Model/Diagnostics.cs",
        "Parser/NodeTests.cs",
        "Lexer/ScannerTables.cs",
    ];

    [Fact]
    public void EveryGeneratedTypeIsPartial()
    {
        var declarations = 0;
        foreach (var file in s_generatedFiles)
        {
            var source = File.ReadAllText(Path.Combine(RepositoryRoot(), "src", "TypeScript.Compiler", file));
            var matches = Regex.Matches(
                source,
                @"^(?:internal|public)\s+(?:static\s+|sealed\s+|abstract\s+|partial\s+)*(?:class|interface|struct|record)\s+\w+",
                RegexOptions.Multiline);

            Assert.NotEmpty(matches);
            declarations += matches.Count;
            Assert.All(matches.Cast<Match>(), match =>
                Assert.True(match.Value.Contains("partial"), $"{file}: '{match.Value}' is not partial"));
        }

        // Sanity check that the pattern above actually matched the expected volume of declarations.
        Assert.True(declarations > 500, $"only {declarations} generated type declarations found");
    }

    /// <summary>
    /// Enums cannot be partial in C#, so they are the one thing the rule does not cover — and the generated enum
    /// files should contain nothing else.
    /// </summary>
    [Fact]
    public void GeneratedEnumsAreNotPartialAndAreTheOnlyExceptions()
    {
        var enumFiles = Directory.GetFiles(
            Path.Combine(RepositoryRoot(), "src", "TypeScript.Compiler", "Model"),
            "*.cs");
        var checkedEnums = 0;
        foreach (var file in enumFiles)
        {
            var source = File.ReadAllText(file);
            if (!source.Contains("<auto-generated>")) continue;

            foreach (Match match in Regex.Matches(source, @"^(?:internal|public)\s+enum\s+\w+", RegexOptions.Multiline))
            {
                checkedEnums++;
                Assert.False(match.Value.Contains("partial"), $"{Path.GetFileName(file)}: '{match.Value}'");
            }
        }

        Assert.True(checkedEnums > 50, $"only {checkedEnums} generated enums found");
    }

    /// <summary>
    /// The worked example: <c>SyntaxList._children</c> comes from the hand-written half, and the generated half must
    /// not also declare it (that would be a duplicate-member error rather than a silent bug, but the point is that the
    /// generator leaves underscore members alone).
    /// </summary>
    [Fact]
    public void SyntaxList_ChildrenComesFromTheHandWrittenHalf()
    {
        var generated = File.ReadAllText(
            Path.Combine(RepositoryRoot(), "src", "TypeScript.Compiler", "Model", "NodeClasses.cs"));
        var handWrittenPath = Path.Combine(RepositoryRoot(), "src", "TypeScript.Compiler", "Model", "SyntaxList.cs");

        Assert.True(File.Exists(handWrittenPath));
        Assert.DoesNotContain("_children", generated);
        Assert.Contains("_children", File.ReadAllText(handWrittenPath));

        // The two halves are one type, so the field is visible through the generated declaration's name.
        Assert.Same(typeof(SyntaxList).GetProperty("_children")!.DeclaringType, typeof(SyntaxList));
    }

    private static string RepositoryRoot()
    {
        var directory = new DirectoryInfo(AppContext.BaseDirectory);
        while (directory is not null && !File.Exists(Path.Combine(directory.FullName, "tsc-cs.slnx")))
        {
            directory = directory.Parent;
        }

        Assert.NotNull(directory);
        return directory!.FullName;
    }
}
